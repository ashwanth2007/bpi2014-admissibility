def _normalise(body):
    """Repair the two malformations that Python escaping keeps producing here.

    Emitting LaTeX from Python string literals is a known trap: a row terminator needs two
    backslashes in the output and therefore four in the source, while a command name needs
    one and therefore two. Getting either wrong produces a file that looks right in a diff
    and fails in the compiler with "Misplaced \noalign". Both malformations are fixed here
    once, so a generator can be written the obvious way and still emit valid LaTeX.
    """
    out = []
    for line in body.split(chr(10)):
        st = line.rstrip()
        # a data row that ends in a single backslash wanted a row break
        if st.endswith(chr(92)) and not st.endswith(chr(92) * 2):
            st = st + chr(92)
        # a doubled thin space is a row break followed by a comma
        st = st.replace(chr(92) * 2 + ",", chr(92) + ",")
        out.append(st)
    return chr(10).join(out)


def write(name, body):
    body = _normalise(body)
    p = OUT / (name + ".tex")
    header = ("%% GENERATED by code/figures/make_tables.py. Do not edit by hand.\n"
              "%% The caption, label and float live in the manuscript; only the numbers are here.\n")
    p.write_text(header + body.rstrip() + "\n", encoding="utf-8", newline="\n")
    MADE.append(name)
    print("  [ok] %-28s %5d bytes" % (name, p.stat().st_size))


def f4(x):
    return "%.4f" % float(x)


def tab_cost():
    m = pd.read_csv(R70 / "model_comparison_leakfree.csv")
    ci = None
    p = DEEP / "bootstrap_ci.csv"
    if p.exists():
        b = pd.read_csv(p)
        ci = {(r.Config, r.Model): (r.CI_low, r.CI_high) for r in b.itertuples()}
    rows = []
    order = ["XGBoost", "LightGBM", "CatBoost", "RandomForest"]
    label = {"RandomForest": "Random forest"}
    for mo in order:
        x = m[m.Model == mo].set_index("Config")["Test_AUC"]
        c, a, t = x["contaminated_v1"], x["leakfree"], x["leakfree_temporal"]
        cost = c - a
        share = 100.0 * cost / (c - 0.5)
        cis = ""
        if ci and ("cost_of_admissibility", mo) in ci:
            lo, hi = ci[("cost_of_admissibility", mo)]
            cis = " [%s, %s]" % (f4(lo), f4(hi))
        bold = (lambda v: r"\textbf{" + f4(v) + "}") if mo == "XGBoost" else f4
        rows.append("%-13s & %s & %s & %s & %s%s & \\SI{%.1f}{\\percent} \\\\"
                    % (label.get(mo, mo), f4(c), bold(a), f4(t), f4(cost), cis, share))
    nf = m.set_index("Config")["Num_Features"].to_dict()
    body = ("\\begin{tabular}{lrrrrr}\n\\toprule\n"
            "Learner & Unconstrained & Admissible & Chronological & Cost (95\\% CI) & Share of signal \\\\\n"
            "\\midrule\n" + "\n".join(rows) + "\n\\midrule\n"
            "Attributes   & %d & %d & %d & & \\\\\n\\bottomrule\n\\end{tabular}"
            % (nf.get("contaminated_v1", 20), nf.get("leakfree", 17), nf.get("leakfree_temporal", 17)))
    write("tab_cost", body)


