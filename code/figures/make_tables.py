def tab_tuning():
    """Tuning and ensembling on the admissible feature set.

    The last hand-typed numeric table in the manuscript, and the most stale: all nine rows
    still carried pre-correction values, including a significance column that said two of the
    five gains were indistinguishable from zero when the current run says all five clear it.
    Both the metrics and the significance verdict are read from the artifacts here, so the
    verdict column can no longer disagree with the interval it is supposed to summarise.
    """
    d = pd.read_csv(R70 / "model_b_tuned_ensemble.csv").set_index("Model")
    sg = pd.read_csv(R70 / "model_b_significance.csv").set_index("Model")

    def best(col, keys):
        vals = {k: float(d.loc[k, col]) for k in keys if k in d.index}
        if not vals:
            return None
        return (min if col == "Brier" else max)(vals, key=vals.get)

    keys = [k for k, _, _ in TUNING_LABEL if k]
    bold_of = {c: best(c, keys) for c in
               ["Test_AUC", "Accuracy", "Precision", "Recall", "F1", "Brier"]}

    def cell(k, col):
        v = f4(d.loc[k, col])
        return "\\textbf{" + v + "}" if bold_of.get(col) == k else v

    rows = []
    for key, label, sig_key in TUNING_LABEL:
        if key is None:
            rows.append("\\midrule")
            continue
        if key not in d.index:
            continue
        delta, verdict = "---", "---"
        if sig_key and sig_key in sg.index:
            dv = float(sg.loc[sig_key, "Diff_vs_untuned"])
            delta = "$%+.4f$" % dv
            verdict = "yes" if bool(sg.loc[sig_key, "Significant"]) else "no"
        rows.append("%-22s & %s & %s & %s & %s & %s & %s & %s & %s \\\\"
                    % (label, cell(key, "Test_AUC"), cell(key, "Accuracy"),
                       cell(key, "Precision"), cell(key, "Recall"), cell(key, "F1"),
                       cell(key, "Brier"), delta, verdict))
    body = ("\\begin{tabular}{lrrrrrrrc}\n\\toprule\n"
            "Model & AUC & Acc. & Prec. & Rec. & $F_1$ & Brier & $\\Delta$ AUC & Sig. \\\\\n"
            "\\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}")
    write("tab_tuning", body)


