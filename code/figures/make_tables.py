"""Generate the manuscript's number tables from the artifacts.

Every table in this paper was hand-typed from a CSV. That is how two defects got in and
survived: a fold mean printed 0.7728 where every artifact says 0.7727, and a standard
deviation printed 0.0051 that matched neither the sample nor the population form. Both sat
inside a verifier tolerance ten times wider than the printed precision, so nothing caught
them. When the dataset was replaced and the protocol corrected, 524 printed numbers went
stale at once, and re-typing 300 of them by hand would have reintroduced the same failure
at a larger scale.

So the tables are generated. Each one is written to `paper/generated/<label>.tex` holding
only the tabular body, and the manuscript keeps its own caption, label and float. That split
matters: the numbers come from the artifacts and cannot drift, while the prose around them
stays a human decision.

    python figures/make_tables.py

Run it after any pipeline change, then rebuild. A table that changes without a run changing
is a bug in this file, not in the paper.
"""
