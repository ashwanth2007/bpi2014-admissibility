def tab_crosslog():
    rows = []
    for d in sorted(CODE.glob("results_*")):
        f = d / "summary.json"
        if not f.exists():
            continue
        s = json.loads(f.read_text(encoding="utf-8"))
        rows.append((s["slug"], s["domain"], s["n_cases"], s["n_groups"],
                     s["breach_rate"], s["best_admissible_auc"], s["share_of_signal_pct"]))
