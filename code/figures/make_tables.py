def _small(x, dp=4):
    """Print a number that would round to a row of zeros in scientific form instead."""
    v = float(x)
    if v != 0.0 and abs(v) < 10.0 ** (-dp):
        return "$\\num{%.1e}$" % v
    return "%.*f" % (dp, v)


def _thousands(x):
    return "\\num{%d}" % int(round(float(x)))


def tab_fitted():
    """Every fitted constant in F1 and F2, with its interval and its support.

    This table was hand-typed and every row of it went stale at once when the dataset was
    replaced and the date parse corrected. Half of the rows are derived quantities (an
    implied half-life, a percentage of a count) that were computed once with a calculator
    and never again, which is the exact failure mode the generated tables exist to remove.
    """
    import math

    f = _fitted()
    lam, urg, exp = f["s5_freshness_decay"], f["s6_urgency_ramp"], f["s3_expertise"]
    hz = _hazard()
    cells = int(exp["eval_shape"][0]) * int(exp["eval_shape"][1])
    half_life = math.log(2.0) / lam["lambda_per_hour"]
    # The tuning note reads "...(earliest 80 per cent) (f1 = 0.5134)". Pull the value that
    # follows "f1 =" rather than the last number in the string, so the 80 in "80 per cent"
    # can never be mistaken for it.
    thr_f1 = ""
    mt = re.search(r"f1\s*=\s*([0-9.]+)", str(hz.get("threshold_tuned_on", "")), re.I)
    if mt:
        thr_f1 = ", $F_1=\\num{%s}$" % mt.group(1)

    rows = [
        "$\\hat{\\lambda}$ & Freshness decay rate, per hour & %s & [%s, %s], $n=\\num{%d}$ \\\\"
        % (_small(lam["lambda_per_hour"]), _small(lam["ci95"][0]), _small(lam["ci95"][1]),
           int(lam["n"])),
        " & \\quad implied half-life (hours) & %.1f & derived from $\\hat{\\lambda}$ \\\\"
        % half_life,
        "$\\hat{k}$ & Urgency ramp steepness & %s & $n=\\num{%d}$ \\\\"
        % (_small(urg["k"]), int(urg["n"])),
        "$\\hat{\\tau}_0$ & Urgency ramp midpoint, hours & $%.2f$ & $n=\\num{%d}$ \\\\"
        % (urg["tau0_hours"], int(urg["n"])),
        "$\\varepsilon$ & Floor applied before any $p\\le0$ aggregation & $10^{-3}$ & fixed, reported as a parameter \\\\",
        "$\\alpha$ & Target-encoding smoothing prior & 20 & fixed \\\\",
        "$\\hat{\\theta}$ & F2 escalation cut point & %s & tuned on train%s \\\\"
        % (_small(hz["threshold"]), thr_f1),
        "\\midrule",
        " & Cosine-expertise cells evaluated & %s & $\\num{%d}\\times\\num{%d}$ \\\\"
        % (_thousands(cells), int(exp["eval_shape"][0]), int(exp["eval_shape"][1])),
        " & \\quad of which exactly zero & %s & \\SI{%.2f}{\\percent} \\\\"
        % (_thousands(exp["exact_zero_cells"]), 100.0 * float(exp["exact_zero_fraction"])),
        " & Delay rows above the \\num{%d}\\,h cap & %s & \\SI{%.1f}{\\percent} of \\num{%d}, a modelling choice \\\\"
        % (int(lam["delay_cap_hours"]), _thousands(lam["rows_excluded_above_cap"]),
           100.0 * float(lam["excluded_fraction"]), int(lam["finite_delay_rows"])),
    ]
    body = ("\\begin{tabular}{lL{5.1cm}rl}\n\\toprule\n"
            "Symbol & Quantity & Estimate & Interval / support \\\\\n\\midrule\n"
            + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}")
    write("tab_fitted", body)


