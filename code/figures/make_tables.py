def tab_logspec():
    """The per-log specification, printed from the file that the code executes.

    The paper claims the decision point, the label and the admissible/inadmissible split were
    fixed for every log before any score was computed on it. A reader has no way to check that
    from prose, and prose is also where it would silently drift away from the code. This table
    is read out of code/log_schemas.py itself, so what the paper shows and what the runner
    obeys are the same object.
    """
    import sys

    if str(CODE) not in sys.path:
        sys.path.insert(0, str(CODE))
    import log_schemas as mod

    def esc(s):
        return (str(s).replace("&", "\\&").replace("_", "\\_")
                .replace("%", "\\%").replace("#", "\\#"))

    def first_sentence(s):
        """The definition, without the paragraphs of rationale that follow it.

        Two of these fields carry several hundred words explaining why a decision point was
        chosen and which obvious alternative was rejected. That belongs in the schema file,
        which a reader can open, and not in a table cell. The caption says where the rest is.
        """
        s = " ".join(str(s).split())
        cut = s.find(". ")
        return s if cut < 0 else s[:cut + 1]

    rows = []
    for slug in LOG_ORDER:
        s = mod.BY_SLUG.get(slug)
        if s is None:
            continue
        n_adm = len(s.admissible_case_attrs)
        n_inadm = len(s.inadmissible_features)
        j = CODE / ("results_%s" % slug) / "summary.json"
        if j.exists():
            d = json.loads(j.read_text(encoding="utf-8"))
            n_adm, n_inadm = int(d["n_admissible"]), int(d["n_inadmissible"])
        rows.append("%s & %s & %s & %s & %d / %d \\\\"
                    % (LOG_SHORT.get(slug, slug), esc(first_sentence(s.decision_point)),
                       esc(first_sentence(s.outcome)), esc(first_sentence(s.group)),
                       n_adm, n_inadm))
    body = ("\\begin{tabular}{L{2.5cm} L{4.0cm} L{3.6cm} L{2.4cm} r}\n\\toprule\n"
            "Log & Decision point $t_{\\mathrm{dec}}$ & Outcome & Rule 2 key & Adm. / inadm. \\\\\n"
            "\\midrule\n" + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}")
    write("tab_logspec", body)


